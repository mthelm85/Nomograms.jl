# Width of a label set in Helvetica at `size`. Measured per character rather than assumed:
# a flat 0.6 em overestimated digits and fractions by up to a quarter -- dropping labels
# that would have fitted -- and underestimated capitals by up to a half, so a title such
# as WAVELENGTH could overlap a neighbour the layout believed clear.
function _textwidth(s::AbstractString, size::Real)
    w = 0.0
    for c in s
        w += get(_ADVANCE, c) do
            textwidth(c) == 2 ? 1.0 : 0.6
        end
    end
    return size * w
end
