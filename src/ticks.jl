"""
    default_tickformat(v) -> String

Format a tick value compactly: integers without a decimal point, everything else to four
significant figures.
"""
function default_tickformat(v::Real)
    x = float(v)
    isfinite(x) || return string(x)
    if x == round(x) && abs(x) < 1e6
        return string(Integer(round(x)))
    end
    s = @sprintf("%.4g", x)
    s = replace(s, "e+0" => "e", "e-0" => "e-")
    return s
end

# Powers of ten from an integer exponent. `10.0^-2.0` goes through exp/log and lands on
# 0.010000000000000002, an error that then shows up in tick values and their labels.
_pow10(e::Integer) = e >= 0 ? 10.0^e : inv(10.0^(-e))

# `m` times a power of ten, kept exact below 1: `3 * inv(10.0)` is 0.30000000000000004,
# whereas dividing gives the 0.3 a reader expects to see.
_mantissa(m::Integer, e::Integer) = e >= 0 ? m * 10.0^e : m / 10.0^(-e)

"""
    nicestep(raw) -> Float64

Round `raw` up to the nearest "nice" tick interval: 1, 2, 2.5 or 5 times a power of ten.
"""
function nicestep(raw::Real)
    raw > 0 || throw(ArgumentError("nicestep needs a positive interval, got $raw"))
    mag = _pow10(floor(Int, log10(raw)))
    frac = raw / mag
    nice = if frac <= 1.0
        1.0
    elseif frac <= 2.0
        2.0
    elseif frac <= 2.5
        2.5
    elseif frac <= 5.0
        5.0
    else
        10.0
    end
    return nice * mag
end

# Multiples of `step` are generated by index rather than by accumulation, so rounding does
# not build up along the axis. The clamp catches the last multiple drifting an ulp past the
# end of the domain, which would otherwise put a tick fractionally off the axis.
function _multiples(lo::Float64, hi::Float64, step::Float64)
    tol = 1e-9 * max(abs(lo), abs(hi), step)
    i0 = ceil(Int, (lo - tol) / step)
    i1 = floor(Int, (hi + tol) / step)
    i1 >= i0 || return Float64[]
    return [clamp(i * step, lo, hi) for i = i0:i1]
end

# How round a number is, measured as the largest multiple of `step` that divides it.
# Majors are offered to the layout in descending roundness so that when an axis is too
# crowded for all of them, 10 survives rather than 9.
function _roundness(v::Float64, step::Float64)
    for m in (1000.0, 500.0, 200.0, 100.0, 50.0, 20.0, 10.0, 5.0, 2.0)
        r = v / (m * step)
        abs(r - round(r)) <= 1e-9 && return m
    end
    return 1.0
end

"""
    linear_ticks(lo, hi; count = 6) -> (majors, minors)

Evenly spaced "nice" values covering `[lo, hi]`, with each major interval subdivided five
ways. Spacing is nice *in the variable*, not on the page: a nomogram axis is usually
non-uniform, and thinning (see [`thin_ticks`](@ref)) decides what actually fits.

`majors` comes back in descending order of roundness rather than ascending by value, which
is the order [`thin_ticks`](@ref) consumes it in.
"""
function linear_ticks(lo::Real, hi::Real; count::Int = 6)
    lo, hi = float(lo), float(hi)
    hi > lo || return (Float64[lo], Float64[])
    step = nicestep((hi - lo) / count)
    majors = _multiples(lo, hi, step)
    minorstep = step / 5
    tol = 1e-9 * step
    minors =
        filter(x -> !any(abs(x - m) <= tol for m in majors), _multiples(lo, hi, minorstep))
    sort!(majors; by = v -> (-_roundness(v, step), abs(v)))
    return (majors, minors)
end

# Decade boundaries first, then halves, then fifths, then the rest -- the order in which
# a crowded logarithmic axis should give its ticks up.
function _log_priority(v::Float64)
    d = floor(Int, log10(v) + 1e-9)
    m = v / _pow10(d)
    isapprox(m, 1.0; atol = 1e-6) && return 0
    isapprox(m, 5.0; atol = 1e-6) && return 1
    isapprox(m, 2.0; atol = 1e-6) && return 2
    # Other whole mantissas before tenths such as 1.5, which only become labels at all on
    # an axis too narrow to hold several whole ones.
    isapprox(m, round(m); atol = 1e-6) && return 3
    return 4
end

"""
    log_ticks(lo, hi) -> (majors, minors)

Ticks for a logarithmic axis: every whole mantissa 1–9 in every decade the range touches,
offered as a major, with tenths between them as minors.

There is deliberately no cut-off for wide ranges. `majors` comes back in the order
[`thin_ticks`](@ref) should try them — decades, then 5s, then 2s, then the rest — and
thinning keeps whatever fits. So a crowded axis settles on decades alone, a less crowded
one on the classic 1-2-5 sequence, and a roomy one labels every mantissa, all from the same
candidates. A fixed rule counting decades could only ever pick one of those, and picked
decades-only for an axis spanning a hair over two.

Every mantissa is also offered as a minor, so one whose label is dropped still gets a tick
mark. On a range too narrow to hold three whole mantissas — 100 to 200 holds only its ends
— the tenths are promoted to majors as well, since otherwise almost nothing is labelled.
"""
function log_ticks(lo::Real, hi::Real)
    lo, hi = float(lo), float(hi)
    (lo > 0 && hi > lo) ||
        throw(ArgumentError("log ticks need 0 < lo < hi, got ($lo, $hi)"))
    dlo = floor(Int, log10(lo))
    dhi = ceil(Int, log10(hi))
    inrange(x) = lo * (1 - 1e-9) <= x <= hi * (1 + 1e-9)
    majors = Float64[]
    tenths = Float64[]
    for d = dlo:dhi
        for m = 1:9
            v = _mantissa(m, d)
            inrange(v) && push!(majors, v)
        end
        for i = 11:99
            i % 10 == 0 && continue
            v = _mantissa(i, d - 1)
            inrange(v) && push!(tenths, v)
        end
    end
    minors = sort!(vcat(majors, tenths))
    length(majors) < 3 && append!(majors, tenths)
    sort!(majors; by = v -> (_log_priority(v), v))
    return (majors, minors)
end

# Whole numbers by roundness -- multiples of 100 before 50 before 10 before 5 -- so on any
# shape of axis the thinning keeps the round ones where it is crowded and fills in where
# it has room. A log-shaped axis gets that from the 1-2-5 order of its mantissas.
function integer_ticks(lo::Real, hi::Real; logshaped::Bool = false)
    lo, hi = float(lo), float(hi)
    keep(xs) = filter(x -> abs(x - round(x)) <= 1e-9 * max(1, abs(x)), xs)
    if logshaped && lo > 0
        majors, minors = log_ticks(lo, hi)
        majors, minors = keep(majors), keep(minors)
        # Halfway values between the leading digits -- 15, 25 between 10, 20, 30 -- are
        # offered after them, so a roomy axis labels them too. Only the 5s: offering every
        # whole number lets the thinning label whichever happen to fit, and 22, 28, 32 in
        # place of 25, 30, 35 reads as noise.
        between = [
            x for
            x in minors if !any(m -> isapprox(m, x), majors) && _roundness(x, 1.0) >= 5
        ]
        sort!(between; by = x -> (-_roundness(x, 1.0), x))
        return ([majors; between], minors)
    end
    i0, i1 = ceil(Int, lo - 1e-9), floor(Int, hi + 1e-9)
    i1 >= i0 || return (Float64[], Float64[])
    # Keep the candidate list bounded on a wide range: a step that is itself a whole number.
    step = max(1, round(Int, nicestep((i1 - i0) / 1000)))
    vals = Float64[k for k = i0:i1 if k % step == 0]
    majors = sort(vals; by = v -> (-_roundness(v, Float64(step)), abs(v)))
    return (majors, vals)
end

"""
    fraction_ticks(lo, hi; maxden = 16) -> (majors, minors)

Every fraction in `[lo, hi]` whose denominator divides `maxden`, offered whole numbers
first (roundest first), then halves, quarters and so on: the order a crowded axis should
give them up, so it keeps `1/2` before `3/8`. Every one is also a minor, so a fraction
whose label is dropped keeps its mark, as on a ruler.
"""
function fraction_ticks(lo::Real, hi::Real; maxden::Integer = 16)
    lo, hi = float(lo), float(hi)
    dens = [d for d = 1:maxden if maxden % d == 0]
    # A range too long for the finest fractions keeps the coarser ones only.
    while length(dens) > 1 && (hi - lo) * dens[end] > 4000
        pop!(dens)
    end
    den = dens[end]
    (hi - lo) * den > 4000 && return integer_ticks(lo, hi)
    n0, n1 = ceil(Int, lo * den - 1e-9), floor(Int, hi * den + 1e-9)
    vals = Float64[n / den for n = n0:n1]
    reduced(v) = denominator(rationalize(Int, v; tol = 0.5 / den^2))
    wholes = [v for v in vals if reduced(v) == 1]
    step =
        isempty(wholes) ? 1.0 : Float64(max(1, round(Int, nicestep(length(wholes) / 1000))))
    majors = sort(vals; by = v -> (reduced(v), -_roundness(v, step), abs(v)))
    return (majors, vals)
end

"""
    fractionformat(maxden = 16; mixed = true) -> (value -> String)

A tick label format for fractions: `1 3/8` (or `11/8` with `mixed = false`), `3/4`, `2`.
A value that is not a whole number of `1/maxden`ths falls back to plain decimals, so an
axis end at 0.3 still reads correctly. The default label format for
`tickstyle = :fraction`; pass it as `tickformat` to label any axis this way.
"""
function fractionformat(maxden::Integer = 16; mixed::Bool = true)
    maxden >= 1 || throw(ArgumentError("maxden must be at least 1, got $maxden"))
    return function (x::Real)
        x = float(x)
        n = round(Int, x * maxden)
        abs(x - n / maxden) <= 1e-9 * max(1, abs(x)) || return default_tickformat(x)
        g = gcd(n, maxden)
        num, den = abs(n) ÷ g, maxden ÷ g
        sign = n < 0 ? "-" : ""
        den == 1 && return sign * string(num)
        whole, part = divrem(num, den)
        (mixed && whole > 0) && return "$sign$whole $part/$den"
        return "$sign$num/$den"
    end
end

# Whether a value may stand as an axis end's label under the variable's tick style: a
# whole number on an integer axis, a fraction on a fraction axis.
function _style_allows(v::Variable, x::Real)
    if v.tickstyle === :integer
        return abs(x - round(x)) <= 1e-9 * max(1, abs(x))
    elseif v.tickstyle === :fraction
        return abs(x * v.maxden - round(x * v.maxden)) <= 1e-9 * max(1, abs(x * v.maxden))
    end
    return true
end

# How important a tick value is on its axis, as `(tier, deepest)`: tier 0 is the most
# important, `deepest` the least, so a tick can be drawn longer the more it matters -- the
# inch, half, quarter of a ruler. The tiers follow the order candidates are offered in.
function _tick_tier(v::Variable, dom::Tuple{Float64,Float64}, x::Float64, level::Int)
    isnothing(v.ticks) || return (level == 1 ? 0 : 1, 1)
    style = resolved_tickstyle(v)
    lo, hi = dom
    if style === :fraction
        dens = [d for d = 1:v.maxden if v.maxden % d == 0]
        length(dens) == 1 && return (0, 0)
        d = denominator(rationalize(Int, x; tol = 0.5 / v.maxden^2))
        i = findfirst(==(d), dens)
        return (isnothing(i) ? length(dens) - 1 : i - 1, length(dens) - 1)
    elseif style === :integer
        r = _roundness(x, 1.0)
        return (r >= 10 ? 0 : r >= 5 ? 1 : 2, 2)
    elseif style === :log && lo > 0
        p = _log_priority(x)
        return (p == 0 ? 0 : p <= 3 ? 1 : 2, 2)
    end
    step = nicestep((hi - lo) / 6)
    r = x / step
    return (abs(r - round(r)) <= 1e-9 * max(1, abs(r)) ? 0 : 1, 1)
end

"""
    candidate_ticks(v::Variable, domain) -> (majors, minors)

Tick values to *try* placing on the axis for variable `v`, honouring any explicit `ticks`
or `minorticks` given on the variable and otherwise picking by
[`tickstyle`](@ref Nomograms.tickstyle).
"""
function candidate_ticks(v::Variable, dom::Tuple{Float64,Float64})
    lo, hi = dom
    tol = 1e-9 * max(abs(lo), abs(hi), hi - lo)
    inside(x) = lo - tol <= x <= hi + tol
    if !isnothing(v.ticks)
        # Explicit ticks keep the order they were given in, which is the user's own
        # statement of which ones matter most if they cannot all fit.
        majors = filter(inside, v.ticks)
        minors = isnothing(v.minorticks) ? Float64[] : filter(inside, v.minorticks)
        return (majors, minors)
    end
    style = resolved_tickstyle(v)
    if style === :integer
        logshaped = tickstyle(v.transform) === :log || _log_shaped(v.transform, dom)
        majors, minors = integer_ticks(lo, hi; logshaped)
    elseif style === :fraction
        majors, minors = fraction_ticks(lo, hi; maxden = v.maxden)
    elseif style === :log && lo > 0
        majors, minors = log_ticks(lo, hi)
    else
        majors, minors = linear_ticks(lo, hi)
    end
    if !isnothing(v.minorticks)
        minors = sort(filter(inside, v.minorticks))
    end
    return (majors, minors)
end
